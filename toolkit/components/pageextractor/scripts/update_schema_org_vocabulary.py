"""
Regenerates SchemaOrgTypes.sys.mjs from a schema.org release.

    ./mach python toolkit/components/pageextractor/scripts/update_schema_org_vocabulary.py --version 30.1
    ./mach lint --fix toolkit/components/pageextractor/SchemaOrgTypes.sys.mjs

Releases are listed at https://github.com/schemaorg/schemaorg/tree/main/data/releases
"""

import argparse
import json
import urllib.request
from pathlib import Path

RELEASE_URL = (
    "https://raw.githubusercontent.com/schemaorg/schemaorg/main/data/releases/"
    "{version}/schemaorg-current-https.jsonld"
)
OUTPUT = Path(__file__).resolve().parent.parent / "SchemaOrgTypes.sys.mjs"
PREFIX = "schema:"

HEADER = """\
/* This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at http://mozilla.org/MPL/2.0/. */

// Generated by toolkit/components/pageextractor/scripts/update_schema_org_vocabulary.py
// from schema.org {version}. Do not edit by hand.

export const SCHEMA_ORG_VERSION = {version_json};

/**
 * Every schema.org type, mapped to its direct parent types.
 *
 * @type {{Record<string, string[]>}}
 */
export const SCHEMA_ORG_TYPE_PARENTS = {{
"""


def as_list(value):
    if value is None:
        return []
    return value if isinstance(value, list) else [value]


def type_parents(graph):
    parents = {}
    for node in graph:
        node_id = node["@id"]
        if "rdfs:Class" not in as_list(node["@type"]) or not node_id.startswith(PREFIX):
            continue
        parents[node_id[len(PREFIX) :]] = [
            parent["@id"][len(PREFIX) :]
            for parent in as_list(node.get("rdfs:subClassOf"))
            if parent["@id"].startswith(PREFIX)
        ]
    return parents


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", required=True, help="e.g. 30.1")
    args = parser.parse_args()

    with urllib.request.urlopen(RELEASE_URL.format(version=args.version)) as response:
        graph = json.load(response)["@graph"]

    parents = type_parents(graph)
    lines = [HEADER.format(version=args.version, version_json=json.dumps(args.version))]
    for name in sorted(parents):
        key = name if name.isidentifier() else json.dumps(name)
        lines.append(f"  {key}: {json.dumps(sorted(parents[name]))},\n")
    lines.append("};\n")
    OUTPUT.write_text("".join(lines))
    print(f"Wrote {len(parents)} types to {OUTPUT}")


if __name__ == "__main__":
    main()
